def sbis_recordset_to_list(result: dict) -> list[dict]:
    """
    Преобразует recordset СБИС из формата d/s
    в обычный список словарей Python.

    СБИС обычно возвращает данные так:

        {
            "d": [
                [1, "ООО Ромашка", "1234567890"],
                [2, "ООО Василек", "9876543210"]
            ],
            "s": [
                {"n": "ID", "t": "Число целое"},
                {"n": "Название", "t": "Строка"},
                {"n": "ИНН", "t": "Строка"}
            ],
            "_type": "recordset",
            "n": True
        }

    Здесь:
        s — описание колонок
        d — строки данных

    Элементы связаны по индексам:

        d[0][0] -> s[0] -> ID
        d[0][1] -> s[1] -> Название
        d[0][2] -> s[2] -> ИНН

    Результат:

        [
            {
                "ID": 1,
                "Название": "ООО Ромашка",
                "ИНН": "1234567890"
            },
            {
                "ID": 2,
                "Название": "ООО Василек",
                "ИНН": "9876543210"
            }
        ]

    Служебные поля СБИС:
        n
        m
        r
        f
        _type

    функция НЕ обрабатывает.

    Пагинация должна обрабатываться отдельно.
    """

    # Схема recordset.
    # Здесь находятся названия всех колонок.
    schema = result.get("s", [])

    # Сами строки данных.
    rows = result.get("d", [])

    records = []

    # Каждая строка из d представляет одну запись.
    for row in rows:

        record = {}

        # Проходим по схеме, а не просто по значениям,
        # потому что именно в s находятся названия полей.
        for index, field in enumerate(schema):

            # Имя колонки.
            #
            # Например:
            # {"n": "ИНН", "t": "Строка"}
            #
            # field_name будет "ИНН".
            field_name = field.get(
                "n",
                f"field_{index}"
            )

            # Берём значение из строки с таким же индексом.
            #
            # s[5] описывает d[row][5].
            if index < len(row):
                value = row[index]
            else:
                # На случай, если схема почему-то длиннее строки.
                value = None

            record[field_name] = value

        records.append(record)

    return records
